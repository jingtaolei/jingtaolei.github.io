#!/usr/bin/env python3
"""Create a lean public directory and preserve only registered cached releases."""
import argparse
from datetime import date, timedelta
import json
from pathlib import Path
import re
import shutil
import tempfile
from urllib.parse import urlsplit
from html.parser import HTMLParser
from prepare_assets import ROOT, prepare, CSS_URL, write_atomic

PAGES = ('index.html', 'privacy.html', 'analytics-check.html')
FINGERPRINT = re.compile(r'^assets/versioned/[\w.-]+\.[a-f0-9]{12}\.[\w]+$')
EXCLUDES = ['README.md', 'maintenance', 'design-notes', 'tools', 'cloudflare-worker',
            'node_modules', 'dist', 'assets/art', 'assets/icons', 'assets/cv', 'assets/portraits',
            'styles.css', 'surfaces.css', 'scene.js', 'interaction.js', 'script.js',
            'version-check.js', 'analytics-config.js', 'collection.js', 'connection-check.js', 'favicon.svg',
            'asset-manifest.json', 'site-build.json', 'package.json', 'package-lock.json',
            '.sass-cache', '.jekyll-cache', 'Gemfile', 'Gemfile.lock', 'vendor',
            '**/__pycache__', '**/*.pyc', '**/.DS_Store',
            'VERSION.json', 'VERSION.md', 'evidence', 'context']


def protected_assets(root=ROOT, today=None):
    today = today or date.today()
    manifest = json.loads((root / 'asset-manifest.json').read_text())
    selected = set(manifest['assets'].values())
    history_path = root / 'tools/published-releases.json'
    history = json.loads(history_path.read_text()).get('releases', []) if history_path.exists() else []
    for i, release in enumerate(history):
        # The most recent live release stays protected even during a long gap between updates.
        if i == 0 or date.fromisoformat(release['retain_until']) >= today:
            selected.update(release['assets'].values())
    for name in selected:
        if not FINGERPRINT.fullmatch(name):
            raise ValueError(f'Invalid fingerprint path: {name}')
        if not (root / name).is_file():
            raise ValueError(f'Missing resource needed by a current/cached release: {name}')
    return selected


class References(HTMLParser):
    def __init__(self):
        super().__init__()
        self.urls = []
    def handle_starttag(self, tag, attrs):
        self.urls.extend(value for key, value in attrs if key in {'src', 'href'} and value)


def publication_files(root=ROOT, today=None):
    selected = protected_assets(root, today)
    files = selected | set(PAGES) | {'site-version.json', 'favicon.ico'}
    for name in PAGES:
        page = References()
        page.feed((root / name).read_text())
        for url in page.urls:
            parts = urlsplit(url)
            if not parts.scheme and not parts.netloc and parts.path:
                target = parts.path.lstrip('/')
                if target not in files:
                    raise ValueError(f'{name} references an omitted publication file: {target}')
    for name in selected:
        if not name.endswith('.css'):
            continue
        for match in CSS_URL.finditer((root / name).read_text()):
            parts = urlsplit(match[2])
            if parts.scheme or parts.netloc or not parts.path:
                continue
            target = (Path(name).parent / parts.path).as_posix()
            if target not in files:
                raise ValueError(f'{name} references an omitted CSS dependency: {target}')
    return files


def config_bytes():
    return ('# Keep developer material in GitHub, outside the public Pages build.\n'
            'exclude:\n' + ''.join(f'  - "{name}"\n' for name in EXCLUDES)).encode()


def build(root=ROOT, check=False, today=None):
    root = root.resolve()
    prepare(root, check=True)
    selected = publication_files(root, today)
    dest = root / 'dist'
    expected = {name: (root / name).read_bytes() for name in selected}
    expected['.build-generated'] = b'Generated by tools/build_site.py; do not edit.\n'
    config = root / '_config.yml'
    if check:
        found = {p.relative_to(dest).as_posix(): p.read_bytes() for p in dest.rglob('*') if p.is_file() and p.name != '.DS_Store'}
        if found != expected or not config.exists() or config.read_bytes() != config_bytes():
            raise ValueError('Publication output is stale; run npm run build.')
    else:
        if dest.exists() and not (dest / '.build-generated').exists():
            raise ValueError('Refusing to replace an unrecognized dist directory.')
        # This destination contains only generated copies; source/history files stay untouched.
        with tempfile.TemporaryDirectory(prefix='.site-build-', dir=root) as tmp:
            staging = Path(tmp) / 'dist'
            for name, data in expected.items():
                write_atomic(staging / name, data)
            if dest.exists():
                shutil.rmtree(dest)
            shutil.move(staging, dest)
        write_atomic(config, config_bytes())
    return {'files': len(selected), 'bytes': sum(len(expected[name]) for name in selected)}


def archive_unused(root=ROOT):
    protected = protected_assets(root)
    archive = root.parent / 'website-archive/unused-fingerprints'
    moved = []
    for path in (root / 'assets/versioned').iterdir():
        if not path.is_file() or path.relative_to(root).as_posix() in protected:
            continue
        if not FINGERPRINT.fullmatch(path.relative_to(root).as_posix()):
            raise ValueError(f'Unexpected versioned file: {path.name}')
        archive.mkdir(parents=True, exist_ok=True)
        destination = archive / path.name
        if destination.exists():
            raise ValueError(f'Archive already contains {path.name}; compare before moving.')
        shutil.move(path, destination)
        moved.append(path.name)
    history_path = root / 'tools/published-releases.json'
    if history_path.exists():
        records = json.loads(history_path.read_text()).get('releases', [])
        keep = [r for i, r in enumerate(records) if i == 0 or date.fromisoformat(r['retain_until']) >= date.today()]
        retired = [r for r in records if r not in keep]
        if retired:
            archive.mkdir(parents=True, exist_ok=True)
            log = archive / 'retired-releases.json'
            earlier = json.loads(log.read_text()) if log.exists() else []
            write_atomic(log, (json.dumps(earlier + retired, indent=2) + '\n').encode())
            write_atomic(history_path, (json.dumps({'releases': keep}, indent=2) + '\n').encode())
    # Aliases for retained files remain available when rebuilding cached HTML snapshots.
    manifest_path = root / 'asset-manifest.json'
    manifest = json.loads(manifest_path.read_text())
    manifest['aliases'] = {name: source for name, source in manifest['aliases'].items() if (root / name).exists()}
    write_atomic(manifest_path, (json.dumps(manifest, indent=2, sort_keys=True) + '\n').encode())
    return moved


def record_published(root=ROOT, commit=None):
    prepare(root, check=True)
    if not commit or not re.fullmatch(r'[a-f0-9]{40}', commit):
        raise ValueError('A verified GitHub commit SHA is required to record a published release.')
    manifest = json.loads((root / 'asset-manifest.json').read_text())
    path = root / 'tools/published-releases.json'
    releases = json.loads(path.read_text()).get('releases', []) if path.exists() else []
    # Grace begins when a successor actually ships, not when someone builds locally.
    if releases:
        releases[0]['retain_until'] = (date.today() + timedelta(days=30)).isoformat()
    record = {'release': manifest['release'], 'commit': commit,
              'retain_until': (date.today() + timedelta(days=30)).isoformat(), 'assets': manifest['assets']}
    releases = [record] + [r for r in releases if r['release'] != record['release']]
    write_atomic(path, (json.dumps({'releases': releases}, indent=2) + '\n').encode())


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--archive-unused', action='store_true', help='Move only unprotected fingerprints into a local archive')
    parser.add_argument('--record-published', metavar='COMMIT', help='Use only after GitHub Pages confirms this release')
    args = parser.parse_args()
    if args.check and (args.archive_unused or args.record_published):
        parser.error('--check cannot be combined with mutations')
    try:
        if args.record_published:
            record_published(commit=args.record_published)
        if args.archive_unused:
            print('Archived:', ', '.join(archive_unused()) or 'nothing')
        print(json.dumps(build(check=args.check)))
    except (ValueError, OSError, json.JSONDecodeError) as exc:
        parser.exit(1, f'{exc}\n')
